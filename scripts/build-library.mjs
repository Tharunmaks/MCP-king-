// Rebuilds data/library.js from rules/*.md(c) and skills/*/SKILL.md so the website can show and copy them
// (works offline and from file://). Run: node scripts/build-library.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const RULE_INFO = {
  'CLAUDE.md': { title: 'CLAUDE.md: token saver for Claude Code', save: 'CLAUDE.md (project root) or ~/.claude/CLAUDE.md (all projects)', ai: 'Claude Code' },
  'AGENTS.md': { title: 'AGENTS.md: universal agent rules', save: 'AGENTS.md (project root)', ai: 'Codex, Cursor, Kimi CLI, OpenCode, Jules, Zed, Windsurf' },
  'GEMINI.md': { title: 'GEMINI.md: rules for Gemini CLI', save: 'GEMINI.md (project root) or ~/.gemini/GEMINI.md', ai: 'Gemini CLI' },
  'cursor-lean.mdc': { title: 'Cursor rule: lean + design', save: '.cursor/rules/lean.mdc', ai: 'Cursor' },
  'copilot-instructions.md': { title: 'Copilot instructions', save: '.github/copilot-instructions.md', ai: 'GitHub Copilot' },
  'design-rules.md': { title: 'Design rules for any AI', save: 'Paste into any chat (ChatGPT, Gemini, Grok, Kimi, Claude app) or a rules file', ai: 'Any AI, phone or PC' },
};
const rules = Object.entries(RULE_INFO).map(([file, info]) => ({ file, ...info, body: fs.readFileSync(path.join(root, 'rules', file), 'utf8') }));
const skills = fs.readdirSync(path.join(root, 'skills')).sort().map((name) => {
  const body = fs.readFileSync(path.join(root, 'skills', name, 'SKILL.md'), 'utf8');
  const desc = (body.match(/^description:\s*(.+)$/m) || [])[1] || '';
  return { name, desc, body };
});
const out = `// Generated by scripts/build-library.mjs from rules/ and skills/. Do not edit by hand.\nwindow.LIBRARY = ${JSON.stringify({ rules, skills }, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'data/library.js'), out);
console.log(`data/library.js: ${rules.length} rules, ${skills.length} skills`);
